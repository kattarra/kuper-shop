-- KuperShop products catalog migration
-- Safe initial import: existing product_key rows are left untouched.
-- Run in Supabase SQL Editor. This does not modify orders or the storefront.

create table if not exists public.products (
  product_key text primary key,
  category text not null,
  brand text not null default '',
  name text not null,
  price integer not null check (price >= 0),
  stock integer not null default 0,
  is_active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.products drop constraint if exists products_stock_check;
alter table public.products add constraint products_stock_check check (stock >= -1);

create index if not exists products_active_sort_idx
  on public.products (is_active, sort_order);

alter table public.products enable row level security;

grant select on public.products to anon, authenticated;
grant insert, update, delete on public.products to authenticated;

drop policy if exists "Public can read active products" on public.products;
create policy "Public can read active products"
  on public.products for select
  using (is_active = true or public.is_shop_admin());

drop policy if exists "Admins can insert products" on public.products;
create policy "Admins can insert products"
  on public.products for insert
  to authenticated
  with check (public.is_shop_admin());

drop policy if exists "Admins can update products" on public.products;
create policy "Admins can update products"
  on public.products for update
  to authenticated
  using (public.is_shop_admin())
  with check (public.is_shop_admin());

drop policy if exists "Admins can delete products" on public.products;
create policy "Admins can delete products"
  on public.products for delete
  to authenticated
  using (public.is_shop_admin());

